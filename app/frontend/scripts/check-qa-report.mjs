import {mkdir} from 'node:fs/promises';
import {createCheckServer} from './browser-check-server.mjs';
import {chromium,expect} from '@playwright/test';

const server=await createCheckServer();
const address=server.httpServer.address();
const output='node_modules/.qa-report-check';
await mkdir(output,{recursive:true});
let browser;
const errors=[];
try{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  for(const width of [1440,390]){
    const page=await browser.newPage({viewport:{width,height:1100}});
    page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(()=>localStorage.setItem('atomforge.session.token','isolated-qa-fixture'));
    await page.route('**/api/v1/studio/runs/qa-fixture/qa-reports',route=>route.fulfill({json:{items:[{id:1,created:'2026-09-16T00:00:00Z',attempt:1,output:{summary:'旧轮次修复反馈',issues:['历史缺陷示例']}}]}}));
    await page.goto(`http://127.0.0.1:${address.port}/scripts/fixtures/qa-report.html`);
    const report=page.getByRole('region',{name:'集中验收报告'});
    await expect(report).toBeVisible();
    await expect(report.getByText('2. 刷新恢复 · 待执行',{exact:true})).toBeVisible();
    await page.getByLabel('报告状态').selectOption('failed');
    await expect(report.getByText('集中反馈 · 2 项',{exact:true})).toBeVisible();
    await expect(report.getByRole('article',{name:'问题 2',exact:true})).toContainText('严重');
    await report.getByRole('button',{name:'严重 1',exact:true}).click();
    await expect(report.getByRole('article')).toHaveCount(1);
    await expect(report.getByText('刷新后任务丢失',{exact:true})).toBeVisible();
    await report.getByText('复现与验证依据',{exact:true}).click();
    await expect(report.getByText('新增一条任务，再刷新页面',{exact:true})).toBeVisible();
    await report.getByRole('button',{name:'全部 2',exact:true}).click();
    await report.getByLabel('问题类型',{exact:true}).selectOption('ui');
    await expect(report.getByRole('article')).toHaveCount(1);
    await expect(report.getByText('删除后计数没有更新',{exact:true})).toBeVisible();
    await report.getByLabel('问题类型',{exact:true}).selectOption('all');
    await expect(report.getByText('2. 刷新恢复 · 失败',{exact:true})).toBeVisible();
    await expect(report.getByText('3. 删除任务 · 阻塞 · 未执行',{exact:true})).toBeVisible();
    await report.getByText('2. 刷新恢复 · 失败',{exact:true}).click();
    await expect(report.getByText('刷新后找不到新增任务',{exact:true})).toBeVisible();
    await expect(report.getByText('外部支付条件未验证',{exact:true})).toBeVisible();
    await page.screenshot({path:`${output}/failed-${width}.png`,fullPage:true});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.getByLabel('报告状态').selectOption('passed');
    await expect(report.getByText('源码审查与全部必需测试已通过。',{exact:true})).toBeVisible();
    await expect(report.getByText('集中反馈 · 2 项',{exact:true})).toHaveCount(0);
    await expect(report.getByText('3. 删除任务 · 通过',{exact:true})).toBeVisible();
    await page.getByLabel('报告状态').selectOption('legacy');
    await expect(report.getByText('1. 独立验收 · 待执行',{exact:true})).toBeVisible();
    await expect(report.getByRole('button',{name:'等级未标注 2',exact:true})).toBeVisible();
    await page.getByLabel('报告状态').selectOption('triaged');
    await expect(report.getByRole('article')).toHaveCount(1);
    await expect(report.getByRole('article')).toContainText('刷新后任务丢失');
    await expect(report.getByText('测试选择器仍需核实',{exact:true})).toBeHidden();
    await expect(report.getByText('变量命名偏好',{exact:true})).toBeHidden();
    await report.getByText('待 QA 核实 · 1 项（不计开发返工）',{exact:true}).click();
    await expect(report.getByText('尚不能确认是测试脚本还是应用问题',{exact:true})).toBeVisible();
    await report.getByText('非阻塞建议 · 1 项（不要求本轮修复）',{exact:true}).click();
    await expect(report.getByText('变量命名偏好',{exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.screenshot({path:`${output}/triaged-${width}.png`,fullPage:true});
    await page.getByLabel('报告状态').selectOption('failed');
    await page.getByLabel('测试完整看板').check();
    await page.getByRole('button',{name:'测试问题 · 2',exact:true}).click();
    await expect(page.getByRole('region',{name:'集中验收报告'})).toBeVisible();
    await expect(page.getByRole('article')).toHaveCount(2);
    const history=page.getByRole('region',{name:'历次修复反馈',exact:true});
    await history.getByText('第 1 次修复反馈 · 1 项问题',{exact:false}).click();
    await expect(history.getByText('历史缺陷示例',{exact:true})).toBeVisible();
    await expect(history.getByRole('button',{name:'等级未标注 1',exact:true})).toBeVisible();
    await page.getByLabel('报告状态').selectOption('passed');
    await expect(history.getByText('历史缺陷示例',{exact:true})).toBeVisible();
    await page.screenshot({path:`${output}/board-${width}.png`,fullPage:true});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.close();
  }
  expect(errors).toEqual([]);
  console.log('QA report browser checks passed at 1440px and 390px: partial, failed, blocked, passed and legacy reports.');
}finally{
  if(browser)await browser.close();
  await server.close();
}
